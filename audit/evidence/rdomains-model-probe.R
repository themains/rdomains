text_mod <- reticulate::import("piedomains.text")
cat("MODEL", text_mod$DEFAULT_TEXT_MODEL, text_mod$DEFAULT_TEXT_REVISION, "\n")
classifier <- text_mod$TextClassifier(cache_dir=tempdir())
