page <- paste(rep("Independent local newspaper reports on elections parliament government policy and international news. Journalists interview elected representatives and investigate public spending.", 5), collapse=" ")
pages <- rdomains:::fetch_row("example.com", "example.com", Sys.time(), status="ok", stage="process", parsed=list(text=page), signals=list(page_state="content",n_tokens=100L))
for (threshold in c(0, 0.99)) {
  cat("THRESHOLD", threshold, "\n")
  result <- pie_cat(pages=pages,threshold=threshold)
  print(result[, c("domain_name","status","stage","pie_category","pie_confidence","label_source","model_repo")])
  print(result$pie_categories)
}
saveRDS(result,"/tmp/rdomains-model-result.rds")
